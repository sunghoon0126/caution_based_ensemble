class BaseDataset(ABC):
    """
    Common base class for datasets. Handles problems list, few-shot examples,
    prompt generation structure, and basic dataset operations.
    """
    def __init__(self, **kwargs):
        super().__init__()
        self.tokenizer_name_or_path = kwargs.get("tokenizer_name_or_path", None)
        # self.system_prompt = kwargs.get("system_prompt", None)
        self.problems: List[BaseProblem] = [] # Use BaseProblem type hint
        self.fewshot_examples: List[BaseProblem] = []
        self.name_or_path = "" # To be set by subclass
        self.prompt_postprocessor_config = kwargs.get("prompt_postprocessor_config", {})
        self.post_processor: Optional[PromptPostprocessor] = None # To be initialized in generate_prompt_text

    def select_fewshot_examples(self, fewshot_dataset: 'BaseDataset', num_shots: int, seed: int = 1):
        """Selects few-shot examples randomly from another dataset."""
        # Need PermutationGenerator, let's define it here or import if it exists elsewhere
        # Assuming it might be needed by multiple dataset types, define it here for now.
        from random import Random # Local import if not needed globally

        class PermutationGenerator:
            def __init__(self, seed) -> None:
                self.random = Random(seed)

            def generate_permutation(self, n, keep_ans=None): # keep_ans might not be relevant for BaseDataset selection
                perm = list(range(n))
                self.random.shuffle(perm)
                # Keep_ans logic is specific to MC augmentation, remove from base selection
                # if keep_ans is not None and len(perm) > keep_ans and perm[keep_ans] != keep_ans:
                #     try:
                #         pos = perm.index(keep_ans)
                #         perm[pos], perm[keep_ans] = perm[keep_ans], perm[pos]
                #     except ValueError: # keep_ans might not be in perm if n is small
                #         pass
                return perm

        if num_shots == 0:
            self.fewshot_examples = []
            return
        if len(fewshot_dataset) == 0:
             logger.warning("Few-shot dataset is empty. Cannot select examples.")
             self.fewshot_examples = []
             return
        if len(fewshot_dataset) < num_shots:
            logger.warning(f"Requested {num_shots} few-shot examples, but dataset only has {len(fewshot_dataset)}. Using all.")
            num_shots = len(fewshot_dataset)

        permutation_generator = PermutationGenerator(seed)
        perm = permutation_generator.generate_permutation(len(fewshot_dataset))
        self.fewshot_examples = [fewshot_dataset[i] for i in perm[:num_shots]]

    @abstractmethod
    def _get_prompt_generation_kwargs(self) -> Dict:
        """Return kwargs specific to the dataset type for PromptPostprocessor."""
        pass

    def generate_prompt_text(self):
        """Generates the full prompt text for each problem instance."""
        if not self.problems:
            logger.warning("No problems in dataset to generate prompts for.")
            return
        
        prompt_kwargs = self.prompt_postprocessor_config
        try:
            self.post_processor = PromptPostprocessor(**prompt_kwargs)
        except Exception as e:
             logger.error(f"Failed to initialize PromptPostprocessor: {e}", exc_info=True)
             # Decide how to handle: proceed without it, or raise error?
             # Raising error seems safer if prompts are essential.
             raise RuntimeError(f"PromptPostprocessor initialization failed: {e}")


        logger.info(f"Generating prompts for {len(self.problems)} problems...")
        for problem in tqdm(self.problems, desc="Generating Prompts"):
            # Allow problems to have pre-assigned prompts
            if problem.prompt is None:
                try:
                    problem.prompt = self.post_processor.get_full_prompt_from_problem(
                        problem=problem, fewshot_examples=self.fewshot_examples
                    )
                except Exception as e:
                     logger.error(f"Failed to generate prompt for problem UUID {problem.uuid}: {e}", exc_info=True)
                     problem.prompt = "[PROMPT GENERATION FAILED]" # Mark as failed

    def __len__(self):
        return len(self.problems)

    def __getitem__(self, idx) -> BaseProblem:
        if idx >= len(self.problems):
             raise IndexError(f"Index {idx} out of range for dataset of length {len(self.problems)}")
        return self.problems[idx]

    def __iter__(self):
        return iter(self.problems)

    def _calculate_hash(self) -> str:
        """Calculates a unique hash for the dataset configuration and problems."""
        problem_hashes = sorted([p.uuid for p in self.problems])
        fewshot_hashes = sorted([p.uuid for p in self.fewshot_examples]) # Sort for consistency

        components = [
            self.__class__.__name__, # Include dataset class name in hash
            "$name_or_path$", str(self.name_or_path),
            "$problems$", "$".join(problem_hashes),
            "$fewshots$", "#".join(fewshot_hashes),
            "$tokenizer$", str(self.tokenizer_name_or_path),
            "$pp$", str(self.prompt_postprocessor_config)
        ]

        # Add specific prompt generation kwargs for hashing
        prompt_kwargs = self._get_prompt_generation_kwargs()
        for key, value in sorted(prompt_kwargs.items()):
             components.append(f"$prompt_{key}$")
             components.append(str(value))


        hashstr = "".join(components)
        try:
            hash_digest = md5(hashstr.encode("utf-8")).digest()
            url_safe_hash = urlsafe_b64encode(hash_digest).rstrip(b"=").decode("utf-8")
            return url_safe_hash
        except Exception as e:
             logger.error(f"Error calculating dataset hash for components {components}: {e}")
             return str(uuid()) # Fallback

    def get_dataset_hash(self) -> str:
        """Returns the calculated hash for the dataset."""
        return self._calculate_hash()

    def select_first_n(self, n: int):
        """Truncates the dataset to the first n problems."""
        if n < 0:
             logger.warning(f"Requested negative number of problems ({n}). Keeping all.")
             return
        if n < len(self.problems):
            logger.info(f"Selecting first {n} problems from {len(self.problems)}.")
            self.problems = self.problems[:n]
        elif n > len(self.problems):
             logger.warning(f"Requested first {n} problems, but dataset only has {len(self.problems)}. Keeping all.")


    def extend(self, other: 'BaseDataset'):
        """Extends the dataset with problems from another dataset."""
        # Check if problem types are compatible? Maybe too strict for base class.
        # Subclasses can override for stricter checks if needed.
        if not isinstance(other, BaseDataset):
             raise TypeError(f"Can only extend with another BaseDataset, not {type(other)}")
        self.problems.extend(other.problems)
        # Note: Few-shot examples are NOT extended. They usually belong to the primary dataset.


