class BaseProblem(ABC):
    """
    Common base class for all problem types.
    Handles hashing, basic attributes, and item access.
    """
    def __init__(
        self,
        problem: Optional[str], # The core question or context
        answer: Any, # Ground truth answer (e.g., index for MC, string for completion)
        parent_uuid: Optional[str] = None,
        generation_config: Optional[Dict] = None,
        extra: Optional[dict] = None,
    ):
        self.problem = problem
        self.answer = answer
        self.parent_uuid = parent_uuid
        self.generation_config = generation_config if generation_config is not None else {}
        self.extra = extra if extra is not None else {}
        self.uuid = self._calculate_hash()
        self.prompt: Optional[str] = None # To be generated by the dataset class

    def _get_hashing_components(self) -> List[Any]:
        """Return components relevant for hashing this specific problem type."""
        # Example base implementation, subclasses should extend or override
        return [
            self.problem,
            "$answer$", str(self.answer), # Convert answer to string for hashing robustness
            "$gen_config$", json.dumps(self.generation_config, sort_keys=True),
            "$extra$", json.dumps(self.extra, sort_keys=True)
        ]

    def _calculate_hash(self) -> str:
        """Calculates a unique hash for the problem instance."""
        components = self._get_hashing_components()
        # Ensure all components are strings for consistent joining
        str_components = [str(comp) if comp is not None else 'None' for comp in components]
        hashstr = "$$".join(str_components)
        try:
            hash_digest = md5(hashstr.encode("utf-8")).digest()
            url_safe_hash = urlsafe_b64encode(hash_digest).rstrip(b"=").decode("utf-8")
            return url_safe_hash
        except Exception as e:
            logger.error(f"Error calculating hash for components {str_components}: {e}")
            # Fallback or re-raise? Using a simple uuid as fallback for now.
            return str(uuid())


    def __hash__(self) -> int:
        """Provides an integer hash for use in sets/dicts."""
        # Note: This integer hash might have collisions, use uuid for uniqueness.
        components = self._get_hashing_components()
        str_components = [str(comp) if comp is not None else 'None' for comp in components]
        hashstr = "$$".join(str_components)
        try:
            hash_digest = md5(hashstr.encode("utf-8")).digest()
            hash_value = int.from_bytes(hash_digest, byteorder="big")
            return hash_value
        except Exception as e:
             logger.error(f"Error calculating integer hash for components {str_components}: {e}")
             return 0 # Fallback hash


    def __getitem__(self, key):
        # Allow dictionary-like access, useful for accessing 'extra' fields etc.
        if hasattr(self, key):
            return getattr(self, key)
        elif key in self.extra:
            return self.extra[key]
        else:
            raise KeyError(f"Key '{key}' not found in problem attributes or extra data.")

    def __setitem__(self, key, value):
        # Allow setting attributes or extra data
        if hasattr(self, key):
            setattr(self, key, value)
        else:
            self.extra[key] = value

    def get_prompt(self) -> Optional[str]:
        """Returns the generated prompt for inference."""
        return self.prompt

    def to_dict(self) -> Dict:
        """Serializes the problem to a dictionary."""
        # Basic serialization, subclasses should override and call super().to_dict()
        return {
            "uuid": self.uuid,
            "parent_uuid": self.parent_uuid,
            "problem": self.problem,
            "answer": self.answer,
            "generation_config": self.generation_config,
            "extra": self.extra,
            "prompt": self.prompt,
            "problem_type": self.__class__.__name__ # Add class name for type info
        }


class SpecialCompletionProblem(BaseProblem):
    """
    Base class for problems requiring free-form completion and correctness checking,
    like math problems (GSM8K) or code generation.
    The 'answer' attribute holds the ground truth completion (e.g., numerical answer string).
    """
    def __init__(
        self,
        problem: str, # The problem description/question
        answer: str, # The ground truth answer string
        parent_uuid: Optional[str] = None,
        generation_config: Optional[Dict] = None,
        extra: Optional[dict] = None,
    ):
        # Ensure answer is stored as a string
        if not isinstance(answer, str):
            logger.warning(f"Expected string answer for SpecialCompletionProblem, got {type(answer)}. Converting to string.")
            if isinstance(answer, list) and len(answer) == 1:
                answer = answer[0]
            answer = str(answer)

        super().__init__(problem, answer, parent_uuid, generation_config, extra)
        # UUID is calculated in BaseProblem constructor

    # Inherits _get_hashing_components from BaseProblem, which should be sufficient
    # unless subclasses need more specific hashing based on their unique fields.

    @abstractmethod
    def check_correctness(self, response: str) -> bool:
        """
        Parses the models's response string, extracts the relevant part,
        and compares it against the ground truth self.answer.
        Must be implemented by subclasses (e.g., GSM8KProblem).

        Returns:
            bool: True if the response is considered correct, False otherwise.
        """
        pass

    def to_dict(self) -> Dict:
        """Serializes the problem to a dictionary."""
        d = super().to_dict()
        # Add any specific fields if needed, otherwise base implementation is fine
        return d


